/** 拼接函数入参：一篇文章的元信息 */
export interface CoverSourcePromptInput {
  title?: string;
  category?: string;
  tags?: string[];
  summary?: string;
}

/**
 * 把海报模板与文章信息拼成源提示词。
 * 只拼接非空字段；最终由后端文本模型据此填充模板占位符。
 */
export function buildCoverSourcePrompt(input: CoverSourcePromptInput): string {
  const title = (input.title ?? "").trim();
  const category = (input.category ?? "").trim();
  const tags = (input.tags ?? []).map(t => t.trim()).filter(Boolean);
  const summary = (input.summary ?? "").trim();

  const infoLines: string[] = [];
  if (title) infoLines.push(`标题：${title}`);
  if (category) infoLines.push(`分类：${category}`);
  if (tags.length > 0) infoLines.push(`标签：${tags.join("、")}`);
  if (summary) infoLines.push(`摘要：${summary}`);

  return [AI_COVER_PROMPT_TEMPLATE, "", "【文章信息】", ...infoLines].join("\n");
}
